import SwiftUI
import Metal
import AVFoundation

struct InfoView: View {
    private let identity = DeviceIdentity.current
    private let cameras = InfoView.availableCameras()

    var body: some View {
        NavigationStack {
            List {
                Section {
                    HeroHeader(
                        systemImage: "iphone.gen3",
                        title: identity.marketingName,
                        subtitle: "iOS \(UIDevice.current.systemVersion)",
                        tint: .blue
                    )
                    .listRowInsets(EdgeInsets())
                    .listRowBackground(Color.clear)
                    .padding(.vertical, 8)
                }

                Section("Device") {
                    InfoRow(label: "Name", value: UIDevice.current.name, icon: "iphone", iconColor: .blue)
                    InfoRow(label: "Model", value: UIDevice.current.model, icon: "square.on.square", iconColor: .gray)
                    InfoRow(label: "iOS Version", value: UIDevice.current.systemVersion, icon: "gearshape", iconColor: .gray)
                }

                Section("Hardware") {
                    InfoRow(label: "Model Identifier", value: DeviceIdentity.rawIdentifier, icon: "number", iconColor: .gray)
                    InfoRow(label: "Chip", value: identity.chip, icon: "cpu", iconColor: .indigo)
                    InfoRow(label: "GPU", value: gpuName, icon: "cpu.fill", iconColor: .purple)
                }

                if !cameras.isEmpty {
                    Section("Cameras") {
                        ForEach(cameras, id: \.name) { camera in
                            InfoRow(label: camera.name, value: camera.position, icon: "camera.fill", iconColor: .pink)
                        }
                    }
                }

                Section("System") {
                    InfoRow(label: "Region", value: regionText, icon: "globe", iconColor: .teal)
                    InfoRow(label: "Language", value: languageText, icon: "character.bubble", iconColor: .teal)
                    InfoRow(label: "Uptime", value: uptimeText, icon: "clock.arrow.circlepath", iconColor: .teal)
                }
            }
            .navigationTitle("Info")
            .navigationBarTitleDisplayMode(.large)
            .toolbar {
                ToolbarItem(placement: .topBarTrailing) {
                    ShareLink(item: deviceReport) {
                        Label("Share", systemImage: "square.and.arrow.up")
                    }
                }
            }
        }
    }

    private var regionText: String {
        guard let code = Locale.current.region?.identifier else { return "Unknown" }
        return Locale.current.localizedString(forRegionCode: code) ?? code
    }

    private var languageText: String {
        guard let code = Locale.current.language.languageCode?.identifier else { return "Unknown" }
        return Locale.current.localizedString(forLanguageCode: code) ?? code
    }

    private var uptimeText: String {
        let seconds = Int(ProcessInfo.processInfo.systemUptime)
        let days = seconds / 86400
        let hours = (seconds % 86400) / 3600
        let minutes = (seconds % 3600) / 60
        if days > 0 { return "\(days)d \(hours)h \(minutes)m" }
        if hours > 0 { return "\(hours)h \(minutes)m" }
        return "\(minutes)m"
    }

    private var deviceReport: String {
        let memory = SystemStats.currentMemory()
        let battery = SystemStats.currentBattery()
        let batteryText = battery.level < 0 ? "Unavailable" : "\(Int(battery.level * 100))%"
        return """
        cpuY Device Report
        —————————————
        Device: \(identity.marketingName)
        Model Identifier: \(DeviceIdentity.rawIdentifier)
        Chip: \(identity.chip)
        GPU: \(gpuName)
        iOS Version: \(UIDevice.current.systemVersion)
        RAM: \(String(format: "%.2f", memory.usedGB)) GB used of \(String(format: "%.2f", memory.totalGB)) GB
        Battery: \(batteryText)
        Region: \(regionText)
        Language: \(languageText)
        Uptime: \(uptimeText)

        Generated by cpuY
        """
    }

    private var gpuName: String {
        MTLCreateSystemDefaultDevice()?.name ?? "Unavailable"
    }

    private static func availableCameras() -> [(name: String, position: String)] {
        let deviceTypes: [AVCaptureDevice.DeviceType] = [
            .builtInWideAngleCamera,
            .builtInUltraWideCamera,
            .builtInTelephotoCamera,
            .builtInTrueDepthCamera
        ]
        let discovery = AVCaptureDevice.DiscoverySession(deviceTypes: deviceTypes, mediaType: .video, position: .unspecified)
        return discovery.devices
            .sorted { lensSortOrder($0.deviceType) < lensSortOrder($1.deviceType) }
            .map { device in
                let position: String
                switch device.position {
                case .back: position = "Back"
                case .front: position = "Front"
                default: position = "Unspecified"
                }
                return (lensLabel(device.deviceType), position)
            }
    }

    private static func lensLabel(_ type: AVCaptureDevice.DeviceType) -> String {
        switch type {
        case .builtInUltraWideCamera: return "Ultra Wide"
        case .builtInWideAngleCamera: return "Wide"
        case .builtInTelephotoCamera: return "Telephoto"
        case .builtInTrueDepthCamera: return "TrueDepth (Face ID)"
        default: return "Camera"
        }
    }

    private static func lensSortOrder(_ type: AVCaptureDevice.DeviceType) -> Int {
        switch type {
        case .builtInUltraWideCamera: return 0
        case .builtInWideAngleCamera: return 1
        case .builtInTelephotoCamera: return 2
        case .builtInTrueDepthCamera: return 3
        default: return 4
        }
    }
}
